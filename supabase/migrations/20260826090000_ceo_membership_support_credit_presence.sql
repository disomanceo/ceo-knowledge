create or replace function public.ceo_presence_heartbeat(client_version text, session_started timestamptz default now())
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode = '42501'; end if;
  insert into public.member_presence(user_id, last_seen_at, session_started_at, app_version)
  values (auth.uid(), now(), coalesce(session_started,now()), left(coalesce(client_version,''),64))
  on conflict (user_id) do update
    set last_seen_at=now(), session_started_at=excluded.session_started_at, app_version=excluded.app_version;
end;
$$;

create or replace function public.ceo_admin_presence_roster()
returns table (user_id uuid, email text, account_status text, online boolean, last_seen_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.email, p.status::text,
         coalesce(mp.last_seen_at >= now() - interval '2 minutes', false),
         mp.last_seen_at
    from public.profiles p
    left join public.member_presence mp on mp.user_id = p.id
   where public.is_admin(auth.uid())
   order by coalesce(mp.last_seen_at >= now() - interval '2 minutes', false) desc,
            lower(p.email);
$$;


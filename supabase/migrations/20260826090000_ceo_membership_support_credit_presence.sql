-- Ceo membership, support, credit, and presence extension for the existing
-- Personal MCP Supabase project. This migration is additive and never touches
-- auth.users credentials.

begin;

create extension if not exists pgcrypto with schema extensions;
create extension if not exists supabase_vault with schema vault;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'ceo_support_hmac_v1') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'ceo_support_hmac_v1',
      'Deterministic Ceo support key HMAC secret'
    );
  end if;
end;
$$;

create or replace function public.ceo_protect_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Keep SQL-editor/maintenance operations possible. Authenticated API callers
  -- must be an approved admin, or may change display_name on their own row only.
  if auth.uid() is null or public.is_admin(auth.uid()) then
    return new;
  end if;

  if old.id = auth.uid()
     and new.id is not distinct from old.id
     and new.email is not distinct from old.email
     and new.status is not distinct from old.status
     and new.role is not distinct from old.role
     and new.support_status is not distinct from old.support_status
     and new.approved_at is not distinct from old.approved_at
     and new.approved_by is not distinct from old.approved_by
     and new.created_at is not distinct from old.created_at then
    return new;
  end if;

  raise exception 'Only display_name may be changed by a member'
    using errcode = '42501';
end;
$$;

drop trigger if exists profiles_ceo_protect_fields on public.profiles;
create trigger profiles_ceo_protect_fields
before update on public.profiles
for each row execute procedure public.ceo_protect_profile_fields();

create table if not exists public.support_licenses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  normalized_email text not null unique check (normalized_email = lower(btrim(normalized_email))),
  key_fingerprint text not null,
  key_version integer not null default 1 check (key_version > 0),
  status text not null default 'ISSUED' check (status in ('ISSUED','ACTIVE','SUSPENDED','REVOKED')),
  plan text not null default 'UNLIMITED' check (plan = 'UNLIMITED'),
  issued_at timestamptz not null default now(),
  issued_by uuid references auth.users(id),
  activated_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.credit_wallet (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance bigint not null default 0 check (balance >= 0),
  total_earned bigint not null default 0 check (total_earned >= 0),
  total_spent bigint not null default 0 check (total_spent >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.credit_transactions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  amount bigint not null check (amount <> 0),
  transaction_type text not null check (transaction_type in ('WELCOME_CREDIT','SPEND','RESERVE','REFUND','ADMIN_GRANT','ADMIN_REMOVE')),
  reason text not null default '',
  balance_after bigint not null check (balance_after >= 0),
  idempotency_key text not null,
  actor_user_id uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique (user_id, idempotency_key)
);

create index if not exists credit_transactions_user_created_idx
  on public.credit_transactions(user_id, created_at desc);

create table if not exists public.member_presence (
  user_id uuid primary key references auth.users(id) on delete cascade,
  last_seen_at timestamptz not null default now(),
  session_started_at timestamptz not null default now(),
  app_version text not null default ''
);

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id),
  target_user_id uuid references auth.users(id),
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_log_created_idx
  on public.admin_audit_log(created_at desc);


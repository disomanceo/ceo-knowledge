create or replace function public.ceo_initialize_member()
returns table (
  user_id uuid,
  email text,
  display_name text,
  account_status text,
  account_role text,
  support_status text,
  support_plan text,
  credit_balance bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  profile_status text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select p.status::text into profile_status
    from public.profiles p where p.id = auth.uid();
  if profile_status is null then
    raise exception 'Member profile not found' using errcode = 'P0002';
  end if;

  if profile_status = 'approved' then
    insert into public.credit_wallet(user_id)
    values (auth.uid()) on conflict (user_id) do nothing;
  end if;

  return query select * from public.ceo_member_snapshot();
end;
$$;

create or replace function public.ceo_support_key(normalized_email text, key_version integer default 1)
returns text
language plpgsql
stable
security definer
set search_path = public, vault
as $$
declare
  secret text;
  encoded text;
begin
  select decrypted_secret into secret
    from vault.decrypted_secrets
   where name = 'ceo_support_hmac_v1'
   order by created_at desc limit 1;
  if coalesce(secret, '') = '' then
    raise exception 'Ceo support HMAC secret is not configured';
  end if;
  encoded := upper(encode(extensions.hmac(
    convert_to('ceo-support:v' || key_version || ':' || lower(btrim(normalized_email)), 'utf8'),
    convert_to(secret, 'utf8'), 'sha256'), 'hex'));
  return 'CEO-' || substr(encoded,1,4) || '-' || substr(encoded,5,4) || '-' || substr(encoded,9,4);
end;
$$;

create or replace function public.ceo_admin_find_member(search_email text)
returns table (user_id uuid, email text, account_status text, account_role text, can_generate boolean)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.email, p.status::text, p.role::text, p.status = 'approved'
    from public.profiles p
   where public.is_admin(auth.uid())
     and lower(btrim(p.email)) = lower(btrim(search_email))
   limit 1;
$$;

create or replace function public.ceo_admin_generate_support(search_email text)
returns table (user_id uuid, email text, support_key text, license_status text, support_plan text)
language plpgsql
security definer
set search_path = public
as $$
declare
  target public.profiles%rowtype;
  normalized text := lower(btrim(search_email));
  raw_key text;
  fingerprint text;
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Approved admin required' using errcode = '42501';
  end if;
  select * into target from public.profiles p
   where lower(btrim(p.email)) = normalized limit 1;
  if target.id is null then
    raise exception 'Account not found' using errcode = 'P0002';
  end if;
  if target.status <> 'approved' then
    raise exception 'Account is not approved' using errcode = '42501';
  end if;

  raw_key := public.ceo_support_key(normalized, 1);
  fingerprint := encode(extensions.digest(convert_to(raw_key, 'utf8'), 'sha256'), 'hex');
  insert into public.support_licenses(user_id, normalized_email, key_fingerprint, key_version, issued_by)
  values (target.id, normalized, fingerprint, 1, auth.uid())
  on conflict (user_id) do update
    set normalized_email = excluded.normalized_email,
        key_fingerprint = excluded.key_fingerprint,
        key_version = excluded.key_version,
        issued_by = coalesce(public.support_licenses.issued_by, excluded.issued_by);

  insert into public.admin_audit_log(actor_user_id, target_user_id, action, metadata)
  values (auth.uid(), target.id, 'SUPPORT_GENERATE', jsonb_build_object('key_version', 1));

  return query
    select target.id, target.email, raw_key, l.status, l.plan
      from public.support_licenses l where l.user_id = target.id;
end;
$$;

create or replace function public.ceo_activate_support(submitted_key text)
returns table (support_status text, support_plan text, activated_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized text;
  fingerprint text;
  license public.support_licenses%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  select lower(btrim(p.email)) into normalized from public.profiles p where p.id = auth.uid();
  fingerprint := encode(extensions.digest(convert_to(upper(btrim(submitted_key)), 'utf8'), 'sha256'), 'hex');
  select * into license from public.support_licenses l where l.user_id = auth.uid() for update;
  if license.id is null or license.normalized_email <> normalized or license.key_fingerprint <> fingerprint then
    raise exception 'Support key does not match this account' using errcode = '42501';
  end if;
  if license.status not in ('ISSUED','ACTIVE') then
    raise exception 'Support license is not activatable' using errcode = '42501';
  end if;
  update public.support_licenses
     set status = 'ACTIVE', activated_at = coalesce(activated_at, now()), revoked_at = null
   where id = license.id;
  insert into public.admin_audit_log(actor_user_id, target_user_id, action)
  values (auth.uid(), auth.uid(), 'SUPPORT_ACTIVATE');
  return query select l.status, l.plan, l.activated_at
    from public.support_licenses l where l.id = license.id;
end;
$$;

create or replace function public.ceo_admin_set_support(target_user uuid, next_status text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare normalized_status text := upper(btrim(next_status));
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Approved admin required' using errcode = '42501';
  end if;
  if normalized_status not in ('ACTIVE','SUSPENDED','REVOKED') then
    raise exception 'Invalid support status';
  end if;
  update public.support_licenses
     set status = normalized_status,
         revoked_at = case when normalized_status = 'REVOKED' then now() else null end,
         activated_at = case when normalized_status = 'ACTIVE' then coalesce(activated_at, now()) else activated_at end
   where user_id = target_user;
  if not found then raise exception 'Support license not found' using errcode = 'P0002'; end if;
  insert into public.admin_audit_log(actor_user_id, target_user_id, action)
  values (auth.uid(), target_user, 'SUPPORT_' || normalized_status);
end;
$$;

create or replace function public.ceo_credit_apply(
  target_user uuid,
  signed_amount bigint,
  tx_type text,
  tx_reason text,
  request_key text,
  actor uuid
)
returns table (balance bigint, unlimited boolean, repeated boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  current_balance bigint;
  prior_balance bigint;
  is_unlimited boolean;
begin
  if coalesce(btrim(request_key), '') = '' then raise exception 'Idempotency key required'; end if;
  select t.balance_after into prior_balance from public.credit_transactions t
   where t.user_id = target_user and t.idempotency_key = request_key;
  if found then return query select prior_balance, false, true; return; end if;

  select exists(select 1 from public.support_licenses l where l.user_id = target_user and l.status = 'ACTIVE')
    into is_unlimited;
  if is_unlimited and signed_amount < 0 then
    select coalesce(w.balance,0) into current_balance from public.credit_wallet w where w.user_id = target_user;
    return query select coalesce(current_balance,0), true, false; return;
  end if;

  insert into public.credit_wallet(user_id) values (target_user) on conflict (user_id) do nothing;
  select w.balance into current_balance from public.credit_wallet w where w.user_id = target_user for update;
  if current_balance + signed_amount < 0 then
    raise exception 'Insufficient credit' using errcode = '22003';
  end if;
  update public.credit_wallet
     set balance = balance + signed_amount,
         total_earned = total_earned + greatest(signed_amount, 0),
         total_spent = total_spent + greatest(-signed_amount, 0),
         updated_at = now()
   where user_id = target_user returning credit_wallet.balance into current_balance;
  insert into public.credit_transactions(user_id, amount, transaction_type, reason, balance_after, idempotency_key, actor_user_id)
  values (target_user, signed_amount, tx_type, coalesce(tx_reason,''), current_balance, request_key, actor);
  return query select current_balance, false, false;
end;
$$;

create or replace function public.ceo_spend_credit(amount bigint, reason text, idempotency_key text)
returns table (balance bigint, unlimited boolean, repeated boolean)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or amount <= 0 then raise exception 'Invalid credit spend'; end if;
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.status='approved') then
    raise exception 'Approved account required' using errcode = '42501';
  end if;
  return query select * from public.ceo_credit_apply(auth.uid(), -amount, 'SPEND', reason, idempotency_key, auth.uid());
end;
$$;


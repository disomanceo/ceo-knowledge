create or replace function public.ceo_member_snapshot()
returns table (
  user_id uuid,
  email text,
  display_name text,
  account_status text,
  account_role text,
  support_status text,
  support_plan text,
  credit_balance bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.email, p.display_name, p.status::text, p.role::text,
         coalesce(l.status, 'NOT_ACTIVATED'),
         case when l.status = 'ACTIVE' then l.plan else null end,
         coalesce(w.balance, 0)
    from public.profiles p
    left join public.support_licenses l on l.user_id = p.id
    left join public.credit_wallet w on w.user_id = p.id
   where p.id = auth.uid();
$$;


create or replace function public.ceo_admin_adjust_credit(target_user uuid, amount bigint, reason text, idempotency_key text)
returns table (balance bigint, unlimited boolean, repeated boolean)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin(auth.uid()) then raise exception 'Approved admin required' using errcode = '42501'; end if;
  if amount = 0 then raise exception 'Credit adjustment cannot be zero'; end if;
  return query select * from public.ceo_credit_apply(
    target_user, amount, case when amount > 0 then 'ADMIN_GRANT' else 'ADMIN_REMOVE' end,
    reason, idempotency_key, auth.uid());
  insert into public.admin_audit_log(actor_user_id, target_user_id, action, metadata)
  values (auth.uid(), target_user, case when amount > 0 then 'CREDIT_GRANT' else 'CREDIT_REMOVE' end,
          jsonb_build_object('amount', amount, 'idempotency_key', idempotency_key));
end;
$$;

